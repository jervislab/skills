#!/bin/bash
# Usage: scaffold-wiki.sh <base_path> <domain> <creator_name>
# Creates the LLM Wiki system structure with template files, plus the root
# inbox.md friction ledger (agent-written, human-consolidated).

set -euo pipefail

BASE="${1:?Usage: scaffold-wiki.sh <base_path> <domain> <creator_name>}"
DOMAIN="${2:?Missing domain}"
CREATOR="${3:?Missing creator_name}"
DATE=$(date +%Y-%m-%d)

mkdir -p "$BASE"/{refs,wiki/{concepts,summaries,entities}}

# .claude/skills — skip if it already exists
if [ ! -d "$BASE/.claude/skills" ]; then
  mkdir -p "$BASE/.claude/skills"
fi

# index.md
cat > "$BASE/wiki/index.md" << INDEXEOF
---
name: Wiki Index
description: Routing table agents use to locate knowledge pages; indexes every skill, concept, summary, and entity entry
last_updated: $DATE
---

Agents locate knowledge pages through this file. Update it after every ingest or new page.

## skills

| Skill | Domain | Entry |
|-------|------|------|

## Concepts

| Page | Description |
|------|------|

## Summaries

| Page | Description |
|------|------|

## Entities

| Page | Description |
|------|------|
INDEXEOF

# log.md
cat > "$BASE/wiki/log.md" << LOGEOF
---
name: Wiki Log
description: Append-only ingest / create / update stream recording each absorption's source path, output pages, and key links
last_updated: $DATE
---

Append-only. Entry format: \`## [YYYY-MM-DD] action | Title\`

Available actions: \`ingest\`, \`query\`, \`lint\`, \`create\`, \`update\`

---

## [$DATE] create | System initialization

Domain: ${DOMAIN}. Core entity: ${CREATOR}. Base structure generated by scaffold-wiki.sh.
LOGEOF

# overview.md — placeholder
cat > "$BASE/wiki/overview.md" << OVERVIEWEOF
---
name: $DOMAIN Overview
description: To be filled — one line on which layers make up this system and what each carries
last_updated: $DATE
---

[Agent fills this file from the results of the bootstrap Ask flow.]
OVERVIEWEOF

# glossary.md — global glossary; establishes "define each custom term in one place"; skip if it already exists
if [ ! -f "$BASE/glossary.md" ]; then
cat > "$BASE/glossary.md" << GLOSSARYEOF
---
name: Global Glossary
description: Defines each project-specific concept in one place, distinct from pre-training knowledge; agents append any coined term not yet listed
last_updated: $DATE
---

## schema

- Precise concept name: concise definition

GLOSSARYEOF
fi

# inbox.md — friction ledger; skip if it already exists
if [ ! -f "$BASE/inbox.md" ]; then
cat > "$BASE/inbox.md" << INBOXEOF
---
name: Friction Inbox
description: Agents log recurring friction during tasks; a human periodically consolidates it into skill Gotchas, AGENTS.md, or scripts, deleting each entry once absorbed with no history kept
last_updated: $DATE
---

One entry per line, appended at the end: \`- [YYYY-MM-DD] scenario: friction → candidate destination\`. When the same friction recurs, append a \`×N\` count to the original entry. Consolidation flow: \`references/friction-inbox.md\` in the wiki-ingest skill.

---
INBOXEOF
fi

# .claude/settings.json — PostToolUse hook runs wiki-lint on every edit; skip if already wired
SKILL_DIR="$(cd "$(dirname "$0")/.." && pwd)"
BASE_ABS="$(cd "$BASE" && pwd)"
# skill inside the project → path via $CLAUDE_PROJECT_DIR, survives clone; global install → absolute path
case "$SKILL_DIR/" in
  "$BASE_ABS"/*) LINT="\$CLAUDE_PROJECT_DIR/${SKILL_DIR#"$BASE_ABS"/}/scripts/wiki-lint.py" ;;
  *)             LINT="$SKILL_DIR/scripts/wiki-lint.py" ;;
esac
python3 - "$BASE/.claude/settings.json" "$LINT" << 'HOOKEOF'
import json, sys
from pathlib import Path
path, lint = Path(sys.argv[1]), sys.argv[2]
settings = json.loads(path.read_text()) if path.exists() else {}
if "wiki-lint.py" not in json.dumps(settings):
    settings.setdefault("hooks", {}).setdefault("PostToolUse", []).append({
        "matcher": "Write|Edit|MultiEdit",
        "hooks": [{"type": "command", "command": f'python3 "{lint}" --hook',
                   "statusMessage": "Checking wiki backlinks...", "timeout": 20}]})
    path.write_text(json.dumps(settings, indent=2, ensure_ascii=False) + "\n")
HOOKEOF

echo "Scaffolded LLM Wiki at $BASE"
echo "Next: fill overview.md, create entity page, sort assets, ingest first source."
